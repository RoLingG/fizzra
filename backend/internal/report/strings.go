// stringsFor 按语言标识取文案表，未知的一律回退到英文
//
// 接受完整的 Accept-Language 头（`zh-CN,zh;q=0.9,en;q=0.8`）而不只是裸语言码，
// 面板的浏览器请求带的正是这个格式。只看第一段并按前缀匹配就够了，报告只有两种语言，
// 完整实现 RFC 4647 的优先级协商换不来任何东西
func stringsFor(lang string) Strings {
	tag := lang
	if i := strings.IndexByte(tag, ','); i >= 0 {
		tag = tag[:i]
	}
	if i := strings.IndexByte(tag, ';'); i >= 0 {
		tag = tag[:i]
	}
	tag = strings.ToLower(strings.TrimSpace(tag))

	switch {
	case strings.HasPrefix(tag, "zh"):
		return zhStrings
	default:
		return enStrings
	}
}

// severityWord 把严重级别映射成该语言下的词
func (s Strings) severityWord(sev model.Severity) string {
	return s.wordFor(string(sev))
}

// wordFor 按取值的字符串形式取词
//
// 同一个概念在两种类型上出现，Issue 上是 model.Severity，聚合出来的 RuleStat 上是
// 普通字符串。模板里两种都要翻，真正查表的是这个按字符串的版本
func (s Strings) wordFor(sev string) string {
	switch model.Severity(sev) {
	case model.SeverityCritical:
		return s.SevCritical
	case model.SeverityError:
		return s.SevError
	case model.SeverityWarning:
		return s.SevWarning
	case model.SeverityInfo:
		return s.SevInfo
	}
	return sev
}
